// Bundles Squiggle's small runtime libraries into app/vendor/ as browser ES
// modules, so the app loads them from its own origin (works offline, and no
// CDN is trusted for these). Run after changing a version in package.json:
//
//   npm run vendor
//
// The large model runtime (LiteRT-LM, ~20-30 MB of WebAssembly) and the
// optional embedding library are NOT vendored; they load from pinned CDN URLs
// in app/src/model/engine.js and app/src/context/embed.js.
import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';

const out = new URL('../app/vendor/', import.meta.url).pathname;
mkdirSync(out, { recursive: true });

const entries = {
  'git.js': `
    import { Buffer } from 'buffer';
    if (!globalThis.Buffer) globalThis.Buffer = Buffer;
    export * as git from 'isomorphic-git';
    export { default as http } from 'isomorphic-git/http/web';
    export { default as LightningFS } from '@isomorphic-git/lightning-fs';
  `,
  'markdown.js': `
    export { marked } from 'marked';
    export { default as DOMPurify } from 'dompurify';
  `,
};

for (const [file, contents] of Object.entries(entries)) {
  await build({
    stdin: { contents, resolveDir: new URL('..', import.meta.url).pathname, loader: 'js' },
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: ['chrome120', 'safari17'],
    minify: true,
    legalComments: 'eof',
    outfile: out + file,
    define: { 'process.env.NODE_ENV': '"production"', global: 'globalThis' },
  });
  console.log('built vendor/' + file);
}

writeFileSync(out + 'README.md',
  'Generated by `npm run vendor` (scripts/vendor.mjs). Do not edit by hand.\n');
